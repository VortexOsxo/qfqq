CREATE TABLE IF NOT EXISTS
  decisionEvents (
    decisionId INTEGER NOT NULL REFERENCES decisions (id) ON DELETE CASCADE,
    userId INTEGER NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    type TEXT NOT NULL,
    data JSONB
  );

CREATE TABLE IF NOT EXISTS
  chats (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    chatName TEXT NOT NULL,
    createdAt TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

ALTER TABLE chats DROP COLUMN IF EXISTS isDirect;

CREATE TABLE IF NOT EXISTS
  chatsUsers (
    chatId INTEGER NOT NULL REFERENCES chats (id) ON DELETE CASCADE,
    userId INTEGER NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    joinedAt TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    leftAt TIMESTAMPTZ,
    PRIMARY KEY (chatId, userId)
  );

CREATE TABLE IF NOT EXISTS
  messages (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    chatId INTEGER NOT NULL REFERENCES chats (id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    sentAt TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    senderId INTEGER NOT NULL,
    FOREIGN KEY (chatId, senderId) REFERENCES chatsUsers (chatId, userId) ON DELETE CASCADE
  );
